package Controlling_Statement;

public class nestedIfElse {
	public static void main(String[] args) {
		
		int no =0;
		
		if(no < 0)
		{
			System.out.println("negative number it is.");
		}
		else if(no ==0)
		{
			System.out.println("zero number it is.");
		}
		else {
			System.out.println("Positive number it is.");
		}
		
		
	}

}
