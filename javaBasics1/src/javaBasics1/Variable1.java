package javaBasics1;

public class Variable1 {

	public static void main(String[] args) {

		
		int a=5; //int type LV
				System.out.println(a);//5
				
				int x=100;  //LV
				System.out.println(x);//100
				
				x=200;  //LV
				System.out.println(x);//updates from 100 to 200
		
		char c='a';//char type LV,single quote
		System.out.println(c);
		
		boolean b=true;  //by default false
		System.out.println(b);//true
		
		System.out.println(2>13);//conditional ,o/p=false or true
		
		int z=13;
		int y=100;
		boolean t=z<y;
		System.out.println(t);  //true
		
		
		
		
		
		
	}

}
