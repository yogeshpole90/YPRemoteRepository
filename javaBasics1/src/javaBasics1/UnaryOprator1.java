package javaBasics1;

public class UnaryOprator1 {

	public static void main(String[] args) {

		 
		int i=1;
		System.out.println(i);
		System.out.println(i++);//1 print ,2 in back
		System.out.println(i++);//2 print ,3 in back
		System.out.println(i);//3 last stored value
		System.out.println(++i);//4,4 in back
		System.out.println(++i);//5 print,5 in back
	    
		int j=i+1;//last val+1=5+1
		System.out.println(j);//6
		
	
	
	}

}
